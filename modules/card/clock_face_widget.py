import PyQt6.QtCore as core
import PyQt6.QtGui as gui
import PyQt6.QtWidgets as widget


class ClockFaceWidget(widget.QWidget):
    """Кастомный виджет для отрисовки минималистичного циферблата часов.
    
    Использует низкоуровневое графическое API Qt (QPainter) для рисования 
    полупрозрачной круглой подложки и 12 засечек по окружности, имитирующих 
    часовые деления. Виджет автоматически адаптируется под любые размеры.
    """
    
    def __init__(self, parent=None):
        """Инициализирует параметры отрисовки циферблата."""
        super().__init__(parent)
        
        # Включает прозрачность для заднего фона виджета. Без этого прямоугольный
        # контейнер виджета имел бы стандартный непрозрачный серый или белый цвет,
        # перекрывая элементы интерфейса, находящиеся под ним.
        self.setAttribute(core.Qt.WidgetAttribute.WA_TranslucentBackground)
        
        # --- Настройки геометрии элементов (в пикселях) ---
        self.TICK_LENGTH = 12  # Длина каждой часовой засечки
        self.TICK_MARGIN = 15  # Отступ от внешнего края круга до начала засечки
        self.TICK_WIDTH = 4    # Толщина линии засечки
        
        # --- Настройки прозрачности (Alpha-канал: от 0 до 255) ---
        self.BG_ALPHA = 45     # Прозрачность темного фонового круга (~17%)
        self.TICK_ALPHA = 150  # Прозрачность белых часовых засечек (~58%)

    def paintEvent(self, event):
        """Автоматически вызывается Qt при необходимости перерисовать виджет.
        
        В этом методе сосредоточена вся математика позиционирования и пошаговая 
        отрисовка векторной графики.
        
        Args:
            event (QPaintEvent): Объект события отрисовки, содержащий область, 
                                 требующую обновления.
        """
        # Создаем экземпляр QPainter — главного инструмента для рисования в Qt.
        # Передаем 'self', указывая, что холстом является текущий виджет.
        self.PAINTER = gui.QPainter(self)
        
        # Включаем антиалиасинг (сглаживание). Это сглаживает "зубчатые" края 
        # окружности и наклонных линий засечек, делая графику плавной.
        self.PAINTER.setRenderHint(gui.QPainter.RenderHint.Antialiasing)

        # --- Расчет динамических размеров ---
        # Получаем текущие размеры виджета (меняются при изменении окна приложения)
        self.WIDTH = self.width()
        self.HEIGHT = self.height()
        
        # Вычисляем центральную точку виджета (координаты X и Y)
        self.CENTER = core.QPointF(self.WIDTH / 2.0, self.HEIGHT / 2.0)
        
        # Вычисляем максимальный радиус круга, который поместится в виджет.
        # Берём минимальную сторону (ширину или высоту), чтобы круг не искажался в овал.
        self.RADIUS = min(self.WIDTH, self.HEIGHT) / 2.0

        # --- Шаг 1: Отрисовка фонового круга ---
        # Задаем "кисть" (Brush) — она отвечает за заливку внутренней области фигур.
        # Создаем черный цвет (0, 0, 0) с заданной ранее прозрачностью.
        self.PAINTER.setBrush(gui.QColor(0, 0, 0, self.BG_ALPHA))
        
        # Отключаем "карандаш" (Pen), который отвечает за контур фигуры,
        # чтобы у фонового круга не было жесткой рамки.
        self.PAINTER.setPen(core.Qt.PenStyle.NoPen)
        
        # Рисуем идеальный круг с центром в self.CENTER и радиусами по осям X и Y
        self.PAINTER.drawEllipse(self.CENTER, self.RADIUS, self.RADIUS)

        # --- Шаг 2: Подготовка к рисованию засечек ---
        # Смещаем координатную сетку. По умолчанию точка (0,0) находится в верхнем
        # левом углу виджета. Метод translate делает точку (0,0) центром нашего круга.
        # Это кардинально упрощает тригонометрические расчеты для засечек.
        self.PAINTER.translate(self.CENTER)
        
        # Настраиваем "карандаш" (Pen) для рисования линий засечек.
        # Задаем белый цвет (255, 255, 255) с полупрозрачностью.
        self.PEN = gui.QPen(gui.QColor(255, 255, 255, self.TICK_ALPHA))
        self.PEN.setWidth(self.TICK_WIDTH)  # Устанавливаем толщину линии
        
        # Делаем концы линий закругленными, чтобы засечки выглядели аккуратнее
        self.PEN.setCapStyle(core.Qt.PenCapStyle.RoundCap)
        
        # Применяем настроенный карандаш к объекту painter
        self.PAINTER.setPen(self.PEN)

        # --- Шаг 3: Циклическая отрисовка 12 засечек ---
        # Циферблат имеет 360 градусов. Нам нужно 12 делений. 
        # Соответственно, шаг поворота составляет: 360 / 12 = 30 градусов.
        for i in range(12):
            # Рисуем вертикальную линию (засечку) строго вверх от нового центра (0,0).
            # Координата X для обеих точек равна 0 (линия строго вертикальная).
            # Координата Y в компьютерной графике направлена вниз, поэтому движение вверх 
            # идет со знаком минус.
            self.PAINTER.drawLine(
                # Начальная точка засечки (ближе к внешнему краю круга)
                core.QPointF(0, -self.RADIUS + self.TICK_MARGIN), 
                # Конечная точка засечки (ближе к центру круга)
                core.QPointF(0, -self.RADIUS + self.TICK_MARGIN + self.TICK_LENGTH)
            )
            
            # Вместо сложных вычислений синусов и косинусов для каждой наклонной линии,
            # мы просто поворачиваем всю координатную сетку холста на 30 градусов по часовой стрелке.
            # Следующая итерация цикла снова нарисует "простую вертикальную" линию, 
            # но на холсте она отобразится уже под нужным углом.
            self.PAINTER.rotate(30.0)
            
        # Завершаем процесс отрисовки и освобождаем системные ресурсы холста.
        self.PAINTER.end()
