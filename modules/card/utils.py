import os
from ..create_path import create_media_path


def get_weather_icon_path(icon_code: str) -> str:
    """Транслирует код иконки OpenWeather в абсолютный путь к локальному файлу.

    Метод сопоставляет стандартные коды API (например, '01d', '10n') или специальные 
    строковые маркеры с именами графических файлов в папке 'weather icon Bl WI'. 
    Выполняет безопасное приведение типов и дополнение числовых индексов нулями.

    Args:
        icon_code (str): Исходный код иконки от OpenWeather API (например, '03n') 
                         или служебный маркер ('sunrise', 'sunset').

    Returns:
        str: Полный файловый путь к PNG-иконке, сгенерированный через create_media_path.
    """
    # Множество служебных маркеров событий, которые не требуют парсинга
    # и имеют фиксированные одноименные названия файлов в ресурсах.
    SPECIAL = {"sunrise", "sunset", "sun2"}

    # Шаг 1: Проверка на специальный маркер (Рассвет/Закат)
    if icon_code in SPECIAL:
        filename = f"{icon_code}.png"  # Имя файла совпадает с кодом (например, "sunrise.png")
    
    # Шаг 2: Обработка стандартных кодов погоды OpenWeather
    else:
        try:
            # Безопасно очищаем строку от случайных пробелов.
            # Если пришел None, заменяем его на пустую строку во избежание AttributeError.
            code = (icon_code or "").strip()
            
            # Стандартный код API всегда состоит минимум из 3 символов: 
            # две цифры типа погоды и одна буква времени суток ('d' — день, 'n' — ночь).
            if len(code) >= 3:
                # Извлекаем первые два символа и приводим к числу (например, '01' -> 1)
                num = int(code[:2])
                
                # Извлекаем третий символ, указывающий на время суток (например, 'd')
                suffix = code[2]
                
                # Форматируем строку по маске '000.x.png'.
                # Спецификатор ':03d' автоматически дополняет число ведущими нулями до 3 знаков:
                # Число 1 превратится в '001', а суффикс 'd' даст в итоге '001.d.png'.
                filename = f"{num:03d}.{suffix}.png"
            
            # Шаг 3: Обработка некорректной длины строки (Защитный Fallback-1)
            else:
                # Если код пришел слишком коротким (например, '1'), просто добавляем '0' в начало
                filename = f"0{code}.png"
                
        # Шаг 4: Перехват исключений (Защитный Fallback-2)
        except Exception:
            # Если упало приведение типов int() (например, в коде оказались буквы там, 
            # где ожидали цифры: 'ABd'), скрипт не упадет, а создаст имя из базового значения.
            filename = f"0{icon_code}.png"

    # Строим и возвращаем итоговый системный путь к файлу внутри папки 'weather icon Bl WI'
    return create_media_path(os.path.join("weather icon Bl WI", filename))
